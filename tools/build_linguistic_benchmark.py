def syl_to_shuangpin(syl: str, scheme: str) -> str:
    if scheme in ("xiaohe", "ziranma") and syl in XIAOHE_ZERO:
        return XIAOHE_ZERO[syl]
    if scheme == "microsoft" and syl in MS_ZERO:
        return MS_ZERO[syl]

    init = ""
    fin = syl
    for two in ("zh", "ch", "sh"):
        if syl.startswith(two):
            init = INIT_MAP[two]
            fin = syl[2:]
            break
    if not init and syl[0] in "bpmfdtnlgkhjqxrzcsyw":
        init = syl[0]
        fin = syl[1:]

    if init in ("j", "q", "x", "y"):
        if fin == "u":
            fin = "v"
        elif fin == "ue":
            fin = "ve"

    fmap = XIAOHE_FIN if scheme == "xiaohe" else (ZIRANMA_FIN if scheme == "ziranma" else MS_FIN)
    return init + fmap[fin]


def to_shuangpin(text: str, scheme: str) -> str:
    return "".join(syl_to_shuangpin(s, scheme) for s in sentence_to_syllables(text))


