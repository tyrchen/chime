def sentence_to_syllables(text: str) -> list[str]:
    """Converts pure Chinese text to normalized toneless Pinyin syllables (`ü` -> `v` except j/q/x/y)."""
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        matched = False
        for span in range(min(6, n - i), 1, -1):
            sub = text[i : i + span]
            if sub in POLYPHONE_OVERRIDES:
                out.extend(POLYPHONE_OVERRIDES[sub])
                i += span
                matched = True
                break
        if matched:
            continue
        syls = lazy_pinyin(text[i], style=Style.NORMAL, v_to_u=False)
        for s in syls:
            s_norm = s.replace("ü", "v").replace("u:", "v")
            if s_norm.startswith(("j", "q", "x", "y")):
                s_norm = s_norm.replace("v", "u")
            out.append(s_norm)
        i += 1
    return out


def to_full_pinyin(text: str) -> str:
    return "".join(sentence_to_syllables(text))


