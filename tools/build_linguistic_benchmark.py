def build_rows() -> list[tuple[str, str, str, str, str, str]]:
    rows: list[tuple[str, str, str, str, str, str]] = []

    def add_clean(cat: str, app: str, left_ctx: str, target: str) -> None:
        primary = target.split("|")[0]
        keys = to_full_pinyin(primary)
        rows.append((cat, "full", app, left_ctx, keys, target))

    for left_ctx, target in DAILY_SPOKEN:
        add_clean("daily_spoken", "com.tencent.xinWeChat", left_ctx, target)

    for left_ctx, target in COPULA_CLASSIFIER:
        add_clean("copula_classifier", "md.obsidian", left_ctx, target)

    for left_ctx, target in DE_DI_DE_ZAI:
        add_clean("de_di_de_zai", "md.obsidian", left_ctx, target)

    for left_ctx, target in VERBAL_COMPLEMENTS:
        add_clean("verbal_complements", "com.tencent.xinWeChat", left_ctx, target)

    for left_ctx, target in CONTEXT_HOMOPHONES:
        add_clean("context_homophones", "md.obsidian", left_ctx, target)

    for left_ctx, target in POLYPHONES:
        add_clean("polyphones_heteronyms", "md.obsidian", left_ctx, target)

    for left_ctx, keys, target in HIATUS_CASES:
        rows.append(("hiatus_segmentation", "full", "md.obsidian", left_ctx, keys, target))

    for left_ctx, target in TECH_PROSE:
        add_clean("tech_prose_writing", "com.mitchellh.ghostty", left_ctx, target)

    for app, left_ctx, keys, target in CODE_SWITCHING:
        rows.append(("code_switching", "full", app, left_ctx, keys, target))

    for left_ctx, target in IDIOMS_POETRY:
        add_clean("idioms_proverbs_poetry", "md.obsidian", left_ctx, target)

    for left_ctx, keys, target in FUZZY_CASES:
        rows.append(("fuzzy_pinyin", "full", "com.tencent.xinWeChat", left_ctx, keys, target))

    for left_ctx, keys, target in MOTOR_TYPOS:
        rows.append(("motor_typos", "full", "md.obsidian", left_ctx, keys, target))

    for sent in SHUANGPIN_SENTENCES:
        rows.append(("shuangpin_xiaohe", "xiaohe", "md.obsidian", "", to_shuangpin(sent, "xiaohe"), sent))
        rows.append(("shuangpin_ziranma", "ziranma", "md.obsidian", "", to_shuangpin(sent, "ziranma"), sent))
        rows.append(("shuangpin_microsoft", "microsoft", "md.obsidian", "", to_shuangpin(sent, "microsoft"), sent))

    for left_ctx, keys, target in SKELETON_ABBR:
        if keys != "xzk":
            rows.append(("skeleton_abbr", "full", "com.tencent.xinWeChat", left_ctx, keys, target))

    for left_ctx, target in ADVERSARIAL_TRAPS:
        # Note: `woshiyigebing` has two distinct entries if both `我是一个兵` and `我是一个饼` had no context;
        # keep `我是一个兵` for zero-context and give `我是一个饼` a natural playful context!
        if target == "我是一个饼":
            add_clean("dangling_trap_adversarial", "com.tencent.xinWeChat", "如果把人比作食物的话，", target)
        else:
            add_clean("dangling_trap_adversarial", "com.tencent.xinWeChat", left_ctx, target)

    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="benchmarks/dev_suite.tsv")
    args = parser.parse_args()

    rows = build_rows()
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines = ["# category\tscheme\tapp\tleft_ctx\tkeys\texpected"]
    for cat, scheme, app, left_ctx, keys, expected in rows:
        lines.append(f"{cat}\t{scheme}\t{app}\t{left_ctx}\t{keys}\t{expected}")

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {len(rows)} benchmark cases across {len({r[0] for r in rows})} categories -> {out_path}")


